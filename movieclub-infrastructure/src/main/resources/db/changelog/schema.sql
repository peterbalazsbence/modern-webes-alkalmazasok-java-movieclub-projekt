CREATE TABLE accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('MEMBER','MODERATOR'))
);
CREATE TABLE movies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL,
 release_year INTEGER NOT NULL CHECK (release_year BETWEEN 0 AND 2200),
 description VARCHAR(4000) NOT NULL,
 external_id BIGINT UNIQUE
);
CREATE TABLE movie_genres (
 movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
 genre VARCHAR(60) NOT NULL,
 PRIMARY KEY(movie_id,genre)
);
CREATE TABLE ratings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
 score INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
 review VARCHAR(2000) NOT NULL,
 CONSTRAINT uq_rating UNIQUE(user_id,movie_id)
);
CREATE TABLE watch_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES accounts(id),
 movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL CHECK (status IN ('PLANNED','WATCHED')),
 CONSTRAINT uq_watch UNIQUE(user_id,movie_id)
);
CREATE INDEX ix_rating_movie ON ratings(movie_id);

